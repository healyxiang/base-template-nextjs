import { test, expect } from "@playwright/test"
test("public homepage, pricing and MDX blog render in English", async ({ page }) => {
  await page.goto("/")
  await expect(page.getByRole("heading", { name: "From idea to launch." })).toBeVisible()
  await page.getByRole("link", { name: "Pricing", exact: true }).first().click()
  await expect(
    page.getByRole("heading", { name: "A little credit goes a long way." })
  ).toBeVisible()
  await page.getByRole("button", { name: "Buy credits" }).first().click()
  await expect(page.getByRole("status")).toContainText("not configured")
  await page.goto("/blog/welcome")
  await expect(page.getByRole("heading", { name: "Welcome to your next launch" })).toBeVisible()
  await expect(page.locator("h2#make-it-yours")).toBeVisible()
  await expect(page.getByRole("link", { name: "Make it yours", exact: true })).toBeVisible()
})
test("Chinese and public workspace, sidebar collapse persists", async ({ page }) => {
  await page.goto("/zh")
  await expect(page.getByRole("heading", { name: "让想法，成为产品。" })).toBeVisible()
  await page.goto("/app/demo")
  await expect(page).toHaveURL(/\/zh\/app\/demo/)
  await page.getByRole("link", { name: "Switch to English" }).click()
  await expect(page.getByRole("heading", { name: "Demo task" })).toBeVisible()
  await expect(page.getByText("This service is not configured yet.")).toBeVisible()
  await page.getByRole("button", { name: "Collapse navigation", exact: true }).click()
  await expect(page.locator(".workspace")).toHaveClass(/is-collapsed/)
  await page.reload()
  await expect(page.getByRole("button", { name: "Expand navigation", exact: true })).toBeVisible()
  await page.getByRole("link", { name: "切换中文" }).click()
  await expect(page).toHaveURL(/\/zh\/app\/demo/)
  await expect(page.getByRole("heading", { name: "示例任务" })).toBeVisible()
})
test("mobile navigation opens, supports Escape and closes after navigation", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/app")
  await page.getByRole("button", { name: "Open navigation" }).click()
  await expect(page.locator("dialog")).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.locator("dialog")).not.toBeVisible()
  await page.getByRole("button", { name: "Open navigation" }).click()
  await page.locator("dialog").getByRole("link", { name: "Demo task" }).click()
  await expect(page).toHaveURL(/\/app\/demo$/)
  await expect(page.locator("dialog")).not.toBeVisible()
})
test("private pages do not index and APIs fail closed without configuration", async ({
  page,
  request,
}) => {
  await page.goto("/app")
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute("content", /noindex/)
  await page.goto("/admin")
  await expect(page.getByText("404", { exact: true })).toBeVisible()
  const account = await request.get("/api/account")
  expect(account.status()).toBe(503)
  const task = await request.post("/api/tasks/demo", { data: { requestId: "bad" } })
  expect(task.status()).toBe(403)
  const admin = await request.get("/api/admin")
  expect(admin.status()).toBe(503)
  const webhook = await request.post("/api/payments/waffo/webhook", { data: {} })
  expect(webhook.status()).toBe(503)
})
test("SEO public URLs exclude private routes and link actual translations", async ({
  request,
  page,
}) => {
  const response = await request.get("/sitemap.xml")
  expect(response.ok()).toBeTruthy()
  const xml = await response.text()
  expect(xml).toContain("/zh/blog/welcome")
  expect(xml).not.toContain("/app")
  expect(xml).not.toContain("/admin")
  await page.goto("/blog/welcome")
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute("href", /\/blog\/welcome$/)
  await expect(page.locator('link[hreflang="zh"]')).toHaveAttribute("href", /\/zh\/blog\/welcome$/)
  expect((await request.get("/wrong-key.txt")).status()).toBe(404)
})
